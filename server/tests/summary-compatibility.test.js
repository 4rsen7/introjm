test('SummaryService uses the original model, prompt and merge flow with an injected provider', async () => {
    const calls = [];
    const service = new SummaryService({ generateText: async (prompt) => {
        calls.push(prompt);
        return '```json\n{"summary":{"generalInsight":"Час доставки знайти складно."},"taskSuccess":[{"task":"Обрати час","outcome":"partial"}]}\n```';
    } });
    const oldSummary = { summary: { generalInsight: 'Старий висновок' }, strengths: ['Зручний пошук адреси'], _system: { transcription: { provider: 'openai' }, status: 'done' } };
    const original = JSON.stringify(oldSummary);
    const result = await service.generate({ transcriptData: TRANSCRIPTS.uk, existingSummaryData: oldSummary, request: { preset: 'prototype_testing' } });
    assert.equal(calls.length, 1);
    assert.equal(sha256(calls[0]), BASELINE_PROMPT_HASHES.uk.prototype_testing);
    assert.equal(DEFAULT_SUMMARY_PROVIDER, 'gemini');
    assert.equal(DEFAULT_SUMMARY_MODEL, 'gemini-2.5-pro');
    assert.equal(result.summary.generalInsight, 'Час доставки знайти складно.');
    assert.equal(result.strengths[0].title, 'Зручний пошук адреси');
    assert.equal(result.taskSuccess[0].outcome, 'partial');
    assert.deepEqual(result._system.transcription, { provider: 'openai' });
    assert.equal(result._system.status, 'done');
    const { generatedAt, ...generation } = result._system.summaryGeneration;
    assert.ok(Number.isFinite(Date.parse(generatedAt)));
    assert.deepEqual(generation, { provider: 'gemini', model: 'gemini-2.5-pro', ...resolveInterviewSummaryRequest({ preset: 'prototype_testing' }) });
    assert.equal(JSON.stringify(oldSummary), original);
});

