test('invalid/empty provider output and provider failures retain existing failure semantics', async () => {
    const args = { transcriptData: TRANSCRIPTS.en };
    const invalidResponses = [];
    const invalid = new SummaryService({ generateText: async () => 'not JSON', onInvalidResponse: (text) => invalidResponses.push(text) });
    await assert.rejects(invalid.generate(args), { message: 'AI returned an invalid response format.' });
    assert.deepEqual(invalidResponses, ['not JSON']);
    for (const output of ['{}', 'null', '[]', '{"_system":{"status":"done"}}']) {
        const empty = new SummaryService({ generateText: async () => output });
        await assert.rejects(empty.generate(args), { message: 'AI returned an empty or unsupported summary format.' });
    }
    const providerError = new Error('Provider unavailable');
    const failing = new SummaryService({ generateText: async () => { throw providerError; } });
    await assert.rejects(failing.generate(args), (error) => error === providerError);
    assert.throws(() => new SummaryService({}), /requires a generateText function/);
});
