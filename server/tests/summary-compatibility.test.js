test('every UA/EN preset and custom prompt is byte-for-byte equivalent to the original pipeline', () => {
    for (const [locale, transcript] of Object.entries(TRANSCRIPTS)) {
        const conversationText = formatInterviewSummaryTranscript(transcript);
        assert.equal(conversationText, transcript.map(line => `[${line.timestamp}] ${line.speaker}: ${line.text}`).join('\n'));
        for (const preset of [...Object.keys(EXPECTED_PRESETS), 'custom']) {
            const request = resolveInterviewSummaryRequest(preset === 'custom' ? CUSTOM_REQUEST : { preset });
            const prompt = buildInterviewSummaryPrompt({ conversationText, ...request });
            assert.equal(sha256(prompt), BASELINE_PROMPT_HASHES[locale][preset], `${locale}/${preset} prompt changed`);
            assert.ok(prompt.includes('Detect the dominant language of the transcript and write the entire output in that exact same language.'));
            assert.ok(prompt.includes('Base every conclusion only on evidence from the transcript.'));
            assert.ok(prompt.endsWith(`Transcript:\n"""\n${conversationText}\n"""`));
        }
    }
});

